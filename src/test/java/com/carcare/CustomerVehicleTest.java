import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;

import java.util.List;

/**
 * Kiểm thử đơn vị cho Sprint 2:
 * S2-01: CSDL và Cấu trúc quan hệ Customers, Vehicles
 * S2-02: CustomerDAO, VehicleDAO, nghiệp vụ US-03 và Bảo mật sở hữu xe
 */
public class CustomerVehicleTest {

    private CustomerDAO customerDAO;
    private VehicleDAO vehicleDAO;

    private int testCustomerId1 = -1;
    private int testCustomerId2 = -1;
    private int testVehicleId1 = -1;
    private int testVehicleId2 = -1;

    @BeforeEach
    public void setUp() {
        customerDAO = new CustomerDAO();
        vehicleDAO = new VehicleDAO();
    }

    @AfterEach
    public void tearDown() {
        // Dọn dẹp dữ liệu thử nghiệm để đảm bảo tính độc lập
        if (testVehicleId1 > 0) {
            vehicleDAO.delete(testVehicleId1);
        }
        if (testVehicleId2 > 0) {
            vehicleDAO.delete(testVehicleId2);
        }
        if (testCustomerId1 > 0) {
            customerDAO.delete(testCustomerId1);
        }
        if (testCustomerId2 > 0) {
            customerDAO.delete(testCustomerId2);
        }
    }

    @Test
    @DisplayName("S2-TC01: Thêm khách hàng mới và tự động sinh mã khách hàng CUST-xxxx")
    public void testInsertCustomerWithAutoGeneratedCode() {
        Customer c = new Customer();
        c.setFullName("Nguyễn Văn Test S2");
        c.setPhone("0988776655");
        c.setEmail("test_s2@example.com");
        c.setAddress("123 Đường Thử Nghiệm, Hà Nội");
        c.setMembershipLevel("STANDARD");

        testCustomerId1 = customerDAO.insert(c);
        Assertions.assertTrue(testCustomerId1 > 0, "Insert customer phai thanh cong va tra ve ID > 0");

        Customer fetched = customerDAO.findById(testCustomerId1);
        Assertions.assertNotNull(fetched, "Khach hang vua tao phai tim thay trong DB");
        Assertions.assertEquals("Nguyễn Văn Test S2", fetched.getFullName());
        Assertions.assertEquals("0988776655", fetched.getPhone());
        Assertions.assertNotNull(fetched.getCustomerCode(), "customerCode phai duoc tu dong sinh");
        Assertions.assertTrue(fetched.getCustomerCode().startsWith("CUST-"), "customerCode phai co dinh dang CUST-xxxx");
    }

    @Test
    @DisplayName("S2-TC02: US-03 Khách hàng cập nhật hồ sơ cá nhân và kiểm tra tính duy nhất số điện thoại")
    public void testCustomerUpdateProfileAndPhoneUniqueness() {
        // Tạo khách hàng 1
        Customer c1 = new Customer();
        c1.setFullName("Trần Khách Một");
        c1.setPhone("0911223344");
        c1.setEmail("khach1@test.com");
        c1.setAddress("Hà Nội");
        c1.setMembershipLevel("SILVER");
        testCustomerId1 = customerDAO.insert(c1);

        // Tạo khách hàng 2
        Customer c2 = new Customer();
        c2.setFullName("Lê Khách Hai");
        c2.setPhone("0922334455");
        c2.setEmail("khach2@test.com");
        c2.setAddress("Hải Phòng");
        c2.setMembershipLevel("STANDARD");
        testCustomerId2 = customerDAO.insert(c2);

        // Khách hàng 1 cập nhật hồ sơ cá nhân (US-03)
        boolean updated = customerDAO.updateProfile(testCustomerId1, "Trần Khách Một Đã Đổi Tên", "0911223344", "khach1_new@test.com", "TP Hồ Chí Minh");
        Assertions.assertTrue(updated, "Update profile cua khach hang phai thanh cong");

        Customer refreshed1 = customerDAO.findById(testCustomerId1);
        Assertions.assertEquals("Trần Khách Một Đã Đổi Tên", refreshed1.getFullName());
        Assertions.assertEquals("TP Hồ Chí Minh", refreshed1.getAddress());
        Assertions.assertEquals("SILVER", refreshed1.getMembershipLevel(), "Hạng thành viên không được bị hạ cấp khi updateProfile");

        // Kiểm tra hàm existsByPhone
        Assertions.assertTrue(customerDAO.existsByPhone("0922334455", testCustomerId1),
                "So dien thoai cua Khach 2 khong duoc cho phep Khach 1 cap nhat trung lap");
        Assertions.assertFalse(customerDAO.existsByPhone("0911223344", testCustomerId1),
                "So dien thoai hien tai cua chinh minh phai hop le (khong bao loi trung)");
    }

    @Test
    @DisplayName("S2-TC03: Thêm xe mới, kiểm tra định dạng và dữ liệu hiển thị chọn xe cho S2-07 (Booking)")
    public void testVehicleInsertAndDisplayNameForBooking() {
        // Tạo khách hàng sở hữu
        Customer c = new Customer();
        c.setFullName("Chủ Xe Test S2");
        c.setPhone("0933445566");
        testCustomerId1 = customerDAO.insert(c);

        // Thêm xe
        Vehicle v = new Vehicle();
        v.setCustomerId(testCustomerId1);
        v.setLicensePlate("30K-999.88");
        v.setBrand("Toyota");
        v.setModel("Camry 2.5Q");
        v.setVehicleType("SEDAN");
        v.setYear(2023);
        v.setColor("Đen bóng");

        testVehicleId1 = vehicleDAO.insert(v);
        Assertions.assertTrue(testVehicleId1 > 0, "Insert vehicle phai thanh cong va co ID > 0");

        Vehicle fetched = vehicleDAO.findById(testVehicleId1);
        Assertions.assertNotNull(fetched, "Phuong tien vua tao phai tim thay");
        Assertions.assertEquals("30K-999.88", fetched.getLicensePlate());
        Assertions.assertEquals("Toyota", fetched.getBrand());
        Assertions.assertEquals("SEDAN", fetched.getVehicleType());
        Assertions.assertEquals("Chủ Xe Test S2", fetched.getCustomerName(), "JOIN voi customers phai lay duoc customer_name");

        // Kiểm tra định dạng hiển thị cho S2-07 Booking selection
        String displayName = fetched.getDisplayName();
        Assertions.assertEquals("Toyota Camry 2.5Q (30K-999.88)", displayName,
                "getDisplayName() phai dung format de dung truc tiep trong combobox dat lich S2-07");
    }

    @Test
    @DisplayName("S2-TC04: Bảo mật phân quyền sở hữu xe (Server-side isOwner Verification)")
    public void testVehicleServerSideOwnershipSecurity() {
        // Khách hàng A
        Customer cA = new Customer();
        cA.setFullName("Khách Hàng A");
        cA.setPhone("0944556677");
        testCustomerId1 = customerDAO.insert(cA);

        // Khách hàng B
        Customer cB = new Customer();
        cB.setFullName("Khách Hàng B");
        cB.setPhone("0955667788");
        testCustomerId2 = customerDAO.insert(cB);

        // Xe thuộc sở hữu của Khách A
        Vehicle vA = new Vehicle();
        vA.setCustomerId(testCustomerId1);
        vA.setLicensePlate("29A-888.88");
        vA.setBrand("Mazda");
        vA.setModel("CX-5");
        vA.setVehicleType("SUV");
        testVehicleId1 = vehicleDAO.insert(vA);

        // Kiểm tra quyền sở hữu phía máy chủ
        Assertions.assertTrue(vehicleDAO.isOwner(testVehicleId1, testCustomerId1),
                "isOwner phai tra ve TRUE cho chu xe that su (Khach A)");

        Assertions.assertFalse(vehicleDAO.isOwner(testVehicleId1, testCustomerId2),
                "isOwner phai tra ve FALSE khi Khach B co y thao tac tren xe cua Khach A (Ngan chan IDOR)");

        // Lấy danh sách xe theo khách hàng: Khách A có 1 xe, Khách B có 0 xe
        List<Vehicle> listA = vehicleDAO.findByCustomerId(testCustomerId1);
        Assertions.assertEquals(1, listA.size(), "Khach A phai co 1 xe");

        List<Vehicle> listB = vehicleDAO.findByCustomerId(testCustomerId2);
        Assertions.assertEquals(0, listB.size(), "Khach B chua co xe nao");
    }

    @Test
    @DisplayName("S2-TC05: Cập nhật thông tin xe và kiểm tra tính duy nhất của biển số")
    public void testVehicleUpdateAndLicensePlateUniqueness() {
        Customer c = new Customer();
        c.setFullName("Chủ Xe Kiểm Tra Biển Số");
        c.setPhone("0966778899");
        testCustomerId1 = customerDAO.insert(c);

        // Xe 1: 51H-111.11
        Vehicle v1 = new Vehicle();
        v1.setCustomerId(testCustomerId1);
        v1.setLicensePlate("51H-111.11");
        v1.setBrand("Honda");
        v1.setModel("CR-V");
        v1.setVehicleType("CUV");
        testVehicleId1 = vehicleDAO.insert(v1);

        // Xe 2: 51H-222.22
        Vehicle v2 = new Vehicle();
        v2.setCustomerId(testCustomerId1);
        v2.setLicensePlate("51H-222.22");
        v2.setBrand("Hyundai");
        v2.setModel("Tucson");
        v2.setVehicleType("CUV");
        testVehicleId2 = vehicleDAO.insert(v2);

        // Kiểm tra trùng biển số
        Assertions.assertTrue(vehicleDAO.existsByLicensePlate("51H-111.11", testVehicleId2),
                "Xe 2 khong duoc doi thanh bien so cua Xe 1");
        Assertions.assertFalse(vehicleDAO.existsByLicensePlate("51H-222.22", testVehicleId2),
                "Bien so hien tai cua chinh Xe 2 phai hop le (khong tinh la trung)");

        // Cập nhật Xe 2 thành công
        Vehicle updateV2 = vehicleDAO.findById(testVehicleId2);
        updateV2.setColor("Trắng ngọc trai");
        updateV2.setYear(2024);
        boolean ok = vehicleDAO.update(updateV2);
        Assertions.assertTrue(ok, "Cap nhat xe 2 phai thanh cong");

        Vehicle refreshed = vehicleDAO.findById(testVehicleId2);
        Assertions.assertEquals("Trắng ngọc trai", refreshed.getColor());
        Assertions.assertEquals(2024, refreshed.getYear());
    }
}
